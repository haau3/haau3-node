// Generates src/generated/ from the pinned spec, openapi/openapi.json:
//
// - openapi.ts: every path, operation and component as types, by openapi-typescript. A component
//   the spec marks as a FHIR resource (its `resourceType` property is a `const`) is typed as
//   @types/fhir's `fhir4.<Type>` instead of from its loose schema, so a FHIR answer carries every
//   element of its resource.
// - methods.ts: one method per operation, named exactly by its operationId, with its doc comment
//   from the operation's summary and description.
// - types.ts: the public names. Each operation's query parameters as `<OperationId>Params`, and every
//   component that is not a FHIR resource (Scheduling's records and answers, Problem) by its own
//   name. A caller never writes `components["schemas"][...]`, so the generator can change without a
//   breaking change.
//
// Run it with `pnpm generate` after `pnpm fetch-spec`. CI runs it again and fails if the output
// differs from what is committed.

import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const SPEC = new URL("../openapi/openapi.json", import.meta.url);
const OUT = new URL("../src/generated/", import.meta.url);

type Json = Record<string, any>;

const HEADER = (what: string) =>
  `// Generated by scripts/generate.ts from openapi/openapi.json. Do not edit by hand.\n// ${what}\n\n`;

const spec = JSON.parse(await readFile(SPEC, "utf8")) as Json;
const schemas = spec.components.schemas as Record<string, Json>;

/** The FHIR resource a component stands for, when the spec marks it with a `resourceType` const. */
function fhirType(schema: Json | undefined): string | undefined {
  const type = schema?.properties?.resourceType?.const;
  return typeof type === "string" ? type : undefined;
}

// --- openapi.ts ---------------------------------------------------------------------------------

const ast = await openapiTS(spec as never, {
  // The FHIR marker (SDK-2): only the component itself becomes `fhir4.<Type>`. The hook is also
  // called for each of its properties with the parent's path, so the path alone is not enough.
  transform(schema, options) {
    const type = fhirType(schema as Json);
    if (type && options.path === `#/components/schemas/${type}`) {
      return ts.factory.createTypeReferenceNode(`fhir4.${type}`);
    }
    return undefined;
  },
  inject: 'import type * as fhir4 from "fhir/r4.js";\n',
});
await writeFile(new URL("openapi.ts", OUT), HEADER("Types for every path, operation and component.") + astToString(ast));

// --- the operations -----------------------------------------------------------------------------

interface Operation {
  id: string;
  method: "GET" | "POST";
  path: string;
  summary: string;
  description: string;
  pathParams: string[];
  hasQuery: boolean;
  queryRequired: boolean;
  hasBody: boolean;
  fhir: boolean;
}

const operations: Operation[] = [];
for (const [path, item] of Object.entries(spec.paths as Record<string, Json>)) {
  for (const method of ["get", "post"] as const) {
    const op = item[method] as Json | undefined;
    if (!op) continue;
    const params = (op.parameters ?? []).filter((p: Json) => !p.$ref) as Json[];
    const query = params.filter((p) => p.in === "query");
    operations.push({
      id: op.operationId,
      method: method.toUpperCase() as "GET" | "POST",
      path,
      summary: op.summary ?? "",
      description: op.description ?? "",
      pathParams: params.filter((p) => p.in === "path").map((p) => p.name as string),
      hasQuery: query.length > 0,
      queryRequired: query.some((p) => p.required),
      hasBody: Boolean(op.requestBody),
      fhir: path.startsWith("/v1/fhir/"),
    });
  }
}
operations.sort((a, b) => a.id.localeCompare(b.id));

const pascal = (id: string) => id[0]!.toUpperCase() + id.slice(1);

/** A doc comment from the spec's own words, which are already published. */
function docComment(op: Operation): string {
  const text = [op.summary, op.description].filter(Boolean).join("\n\n").replaceAll("*/", "*\\/");
  const lines = text.split("\n").map((line) => (line ? `   * ${line}` : "   *"));
  return [`  /**`, ...lines, "   *", `   * \`${op.method} ${op.path}\``, "   */"].join("\n");
}

// --- methods.ts ---------------------------------------------------------------------------------

const methodLines: string[] = [];
for (const op of operations) {
  const args: string[] = [];
  for (const name of op.pathParams) args.push(`${name}: string`);
  if (op.hasQuery) args.push(`params${op.queryRequired ? "" : "?"}: ${pascal(op.id)}Params`);
  if (op.hasBody) args.push(`body: BodyOf<"${op.id}">`);
  args.push("options?: RequestOptions");
  const call = [
    `method: "${op.method}"`,
    `path: ${JSON.stringify(op.path)}`,
    op.pathParams.length ? `pathParams: { ${op.pathParams.join(", ")} }` : undefined,
    op.hasQuery ? "query: params" : undefined,
    op.hasBody ? "body" : undefined,
  ].filter(Boolean);
  methodLines.push(
    docComment(op),
    `  ${op.id}(${args.join(", ")}): Promise<ResponseOf<"${op.id}">> {`,
    `    return this.operation<ResponseOf<"${op.id}">>({ ${call.join(", ")} }, options);`,
    "  }",
    "",
  );
}

const methods = `${HEADER("One method per operation, named by its operationId.")}import type { BodyOf, ResponseOf } from "../operations.js";
import type { RequestOptions } from "../transport.js";
import { Transport } from "../transport.js";
import type {
${operations
  .filter((op) => op.hasQuery)
  .map((op) => `  ${pascal(op.id)}Params,`)
  .join("\n")}
} from "./types.js";

/** Every operation of the haau3 platform API. {@link Haau3} is the class to construct. */
export abstract class Operations extends Transport {
${methodLines.join("\n").trimEnd()}
}
`;
await writeFile(new URL("methods.ts", OUT), methods);

// --- types.ts -----------------------------------------------------------------------------------

const ownComponents = Object.keys(schemas)
  .filter((name) => !fhirType(schemas[name]))
  .sort();

const types = `${HEADER("The public type names.")}import type { QueryOf } from "../operations.js";
import type { components } from "./openapi.js";

${ownComponents.map((name) => `export type ${name} = components["schemas"]["${name}"];`).join("\n")}

${operations
  .filter((op) => op.hasQuery)
  .map((op) => `/** The query parameters of \`${op.id}\`. */\nexport type ${pascal(op.id)}Params = QueryOf<"${op.id}">;`)
  .join("\n")}
`;
await writeFile(new URL("types.ts", OUT), types);

console.log(
  `Generated ${operations.length} methods, ${ownComponents.length} component names and ` +
    `${operations.filter((op) => op.hasQuery).length} parameter types from ${spec.info.version}.`,
);
