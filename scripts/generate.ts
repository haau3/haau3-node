// --- api.md -------------------------------------------------------------------------------------

/** How a method is called, as a reader writes it: `readInsurancePlan(id)`, `searchSlots(params?)`. */
function signature(op: Operation): string {
  const args = [...op.pathParams];
  if (op.hasQuery) args.push(op.queryRequired ? "params" : "params?");
  if (op.hasBody) args.push("body");
  return `${op.id}(${args.join(", ")})`;
}

/** What api.md says of the options an operation's declared headers add. */
function headerOptionsSentence(): string {
  if (!withHeaders.length) return "";
  const each = withHeaders.flatMap((op) => op.headers.map((h) => `\`${op.id}\` takes \`${h.option}\`, sent as \`${h.name}\``));
  return `\nAn operation that declares a header takes it as one more option, named from the header and checked\nbefore sending: ${each.join("; ")}.\n`;
}

const tagOrder = ((spec.tags ?? []) as Json[]).map((t) => t.name as string);
const tagText = new Map(((spec.tags ?? []) as Json[]).map((t) => [t.name as string, (t.description ?? "") as string]));
const byTag = new Map<string, Operation[]>();
for (const op of [...operations].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))) {
  byTag.set(op.tag, [...(byTag.get(op.tag) ?? []), op]);
}
const sections = [...byTag.keys()]
  .sort((a, b) => (tagOrder.indexOf(a) + 1 || 99) - (tagOrder.indexOf(b) + 1 || 99))
  .map((tag) => {
    const rows = byTag
      .get(tag)!
      .map((op) => `| [\`${signature(op)}\`](${op.docs}) | \`${op.method} ${op.path}\` | ${op.summary} |`);
    return [`## ${tag}`, "", tagText.get(tag) ?? "", "", "| Method | Request | What it does |", "|---|---|---|", ...rows].join("\n");
  });

